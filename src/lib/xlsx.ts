import { strToU8, zipSync } from 'fflate';
import { APP_NAME, COMPANY } from './appInfo';

// A small .xlsx writer: one or more sheets, a styled header row, frozen header, auto filter and sensible column widths.

export type Cell = string | number | null | undefined;
export type Sheet = { name: string; title?: string; columns: { header: string; width?: number; money?: boolean }[]; rows: Cell[][]; totals?: Cell[] };

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');

function colName(i: number) {
  let s = '';
  for (i += 1; i > 0; i = Math.floor((i - 1) / 26)) s = String.fromCharCode(65 + ((i - 1) % 26)) + s;
  return s;
}

// Style ids (see styles.xml below): 0 normal, 1 header, 2 money, 3 title, 4 total label, 5 total money
function cell(ref: string, v: Cell, style = 0) {
  const s = style ? ` s="${style}"` : '';
  if (v === null || v === undefined || v === '') return style ? `<c r="${ref}"${s}/>` : '';
  if (typeof v === 'number' && isFinite(v)) return `<c r="${ref}"${s}><v>${v}</v></c>`;
  return `<c r="${ref}"${s} t="inlineStr"><is><t xml:space="preserve">${esc(String(v))}</t></is></c>`;
}

function sheetXml(sh: Sheet) {
  const cols = sh.columns;
  const widths = cols.map((c, i) => c.width ?? Math.min(48, Math.max(c.header.length + 2, ...sh.rows.slice(0, 200).map((r) => String(r[i] ?? '').length + 2), 8)));
  const rows: string[] = [];
  let r = 1;
  if (sh.title) {
    rows.push(`<row r="${r}" ht="22" customHeight="1">${cell('A' + r, sh.title, 3)}</row>`);
    r++;
    rows.push(`<row r="${r}">${cell('A' + r, `${COMPANY} · generated ${new Date().toLocaleString('en-GB')}`)}</row>`);
    r += 2;
  }
  const headRow = r;
  rows.push(`<row r="${r}" ht="20" customHeight="1">${cols.map((c, i) => cell(colName(i) + r, c.header, 1)).join('')}</row>`);
  r++;
  for (const row of sh.rows) {
    rows.push(`<row r="${r}">${cols.map((c, i) => cell(colName(i) + r, row[i], c.money && typeof row[i] === 'number' ? 2 : 0)).join('')}</row>`);
    r++;
  }
  if (sh.totals) {
    rows.push(`<row r="${r}">${cols.map((c, i) => cell(colName(i) + r, sh.totals![i], c.money ? 5 : 4)).join('')}</row>`);
  }
  const last = colName(cols.length - 1);
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheetViews><sheetView workbookViewId="0"><pane ySplit="${headRow}" topLeftCell="A${headRow + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>
<cols>${widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>
<sheetData>${rows.join('')}</sheetData>
${sh.rows.length ? `<autoFilter ref="A${headRow}:${last}${headRow + sh.rows.length}"/>` : ''}
<pageSetup orientation="landscape" paperSize="9" fitToWidth="1" fitToHeight="0"/>
</worksheet>`;
}

